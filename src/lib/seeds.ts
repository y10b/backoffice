/**
 * 자동 생성이 돌려 쓰는 시드 키워드.
 *
 * 라우트 파일은 Next 가 정한 이름(GET/POST/dynamic …)만 export 할 수 있어서 여기로 뺐다.
 * 덕분에 순수 함수로 따로 테스트할 수도 있다.
 *
 * 고른 기준은 애드센스 단가다. 실측에서 보험·법률이 39,894원, 재테크·생활정보가
 * 5,000원대였고 테크는 2,273원이었다. 개인 블로그가 감당할 만한 난이도까지 감안해
 * 재테크·정부지원금·보험 쪽으로 채웠다.
 */
export const SEED_POOL = [
  "연말정산",
  "근로장려금",
  "정부지원금",
  "실업급여",
  "국민연금",
  "건강보험료",
  "청년지원금",
  "소상공인 정책자금",
  "주택청약",
  "전세자금대출",
  "자동차보험",
  "실손보험",
];

/**
 * 날짜로 시드를 고른다.
 *
 * 무작위로 뽑으면 같은 날 두 번 돌렸을 때 다른 주제가 나와 중복 글이 쌓인다.
 * 날짜를 나눗셈해 쓰면 하루 안에서는 항상 같은 시드가 나오고, 풀 크기만큼의 주기로 돈다.
 */
export function seedForDate(d: Date, pool: string[] = SEED_POOL): string {
  const days = Math.floor(d.getTime() / 86_400_000);
  return pool[days % pool.length];
}
